#pragma once
// 꾸미포토 부스 리모컨 설정 — **이 파일만 고치면 된다**(main.cpp 는 건드리지 않는다).

// ── 이름 ──────────────────────────────────────────────────────────
// GATT 모드에서 알리는 이름. 앱은 **이름이 아니라 서비스 UUID 로** 찾으므로 이름은
// 사람이 보기 위한 것이다(아이패드 관리 화면의 '연결됨 — …' 에 이 이름이 뜬다).
#define DEVICE_NAME "JdSnap Remote"
// HID(블루투스 키보드) 모드에서 기기 설정의 블루투스 목록에 뜨는 이름.
// 거기서 사람이 골라 페어링해야 하므로 **GATT 쪽과 달리 이름이 중요하다.**
#define DEVICE_NAME_HID "JdSnap Remote KB"

// ── 단추 ──────────────────────────────────────────────────────────
// 단추는 **GND 로 떨어뜨린다**(핀 → 단추 → GND). 내부 풀업을 쓰므로 저항이 필요 없다.
//
//   C3 SuperMini        부스 단추(아케이드 단추)
//     GPIO3  ───────────  단추 한쪽
//     GND    ───────────  단추 다른 쪽
//
// ⚠ **GPIO2·8·9 에 단추를 달지 말 것** — 부팅 스트래핑 핀이라, 켜는 순간 단추가 눌려
//   있으면 보드가 다운로드 모드로 들어가 펌웨어가 돌지 않는다. GPIO18·19 는 USB 다.
#define PIN_BUTTON          3
// 두 번째 단추('처음으로' 전용). **없으면 -1** — 그때는 단추 하나를 길게 눌러 대신한다.
#define PIN_BUTTON_BACK    -1
#define BUTTON_ACTIVE_LOW   1     // 1 = 누르면 LOW(GND 로 떨어진다) · 0 = 누르면 HIGH
#define DEBOUNCE_MS        30     // 접점이 떠는 동안 무시하는 시간
// 단추가 하나일 때, 이만큼 누르고 있으면 '처음으로' 가 된다(짧게 누르면 셔터).
// 두 번째 단추를 달았으면 이 값은 쓰이지 않는다.
#define LONG_PRESS_MS     700

// ── 알림 LED ──────────────────────────────────────────────────────
// C3 SuperMini 의 **온보드 LED 는 GPIO8** 이고 LOW 일 때 켜진다.
// 부스 단추 안에 든 LED 를 쓰려면 그 핀으로 바꾼다(없애려면 -1).
// 무엇을 어떻게 깜빡이는지는 main.cpp 의 `ledTick` 표에 있다.
#define PIN_LED             8
#define LED_ACTIVE_LOW      1

// ── 부저 (쓰지 않으면 -1) ─────────────────────────────────────────
// 카운트다운을 같이 세어 준다. **GATT 모드에서만 소리가 난다** — HID(키보드)로 붙으면
// 앱이 기기에게 아무것도 돌려줄 수 없어서 리모컨은 지금 몇 초인지 모른다.
#define PIN_BUZZER         -1
#define BUZZER_ACTIVE_HIGH  1     // 1 = HIGH 로 울린다(패시브 부저는 tone 으로 울린다)
#define BUZZER_PASSIVE      1     // 1 = 수동(패시브) 부저 — 음 높이를 낸다 / 0 = 능동

// ── 어느 길로 붙을지 ──────────────────────────────────────────────
// 한 벌을 구워 두고 **보드에서 길을 바꾼다**(NVS 에 남아 다음에 켜도 그대로다):
//   · 단추를 누른 채로 보드를 켜고 MODE_TOGGLE_HOLD_MS 만큼 쥐고 있는다
//   · 또는 시리얼에 `m` 을 넣는다
// 둘을 한 보드에서 **같이** 쓸 수는 없다 — HID 는 아이패드에 페어링된 키보드라야 하고
// (전용 서비스와 한 기기에 섞으면 페어링 창이 엉킨다), 앱은 두 길을 같이 켜 둘 수 있으니
// 리모컨 쪽에서 하나만 고르면 된다.
#define DEFAULT_MODE_HID    0     // 0 = GATT(권함) · 1 = HID 키보드
#define MODE_TOGGLE_HOLD_MS 3000

// ── 전지로 쓸 때 ──────────────────────────────────────────────────
// 붙어 있는 동안 ~15mA 라 18650 하나로 하루가 넘는다. 부스 자리에 USB 를 끌 수 있으면
// 그게 제일 편하다 — 깊은 잠(deep sleep)은 **일부러 쓰지 않는다**: 깨어나 다시 붙는 데
// 1~2초가 걸려 첫 누름이 먹히지 않는다. 줄 선 부스에서 그게 제일 나쁘다.
#define TX_POWER_DBM        3     // 3dBm. 부스 안이라 멀리 쏠 일이 없다(0~9 사이)
