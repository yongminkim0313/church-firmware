#pragma once
// ─────────────────────────────────────────────────────────────────
// 소리 — 미리 구워 둔 토막을 이어 읽는다 (v2: microSD + MAX98357A · I2S)
//
// 합성은 하지 않는다. ESP32 가 microSD 의 WAV 를 번호로 찾아 읽어 I2S 앰프로 낸다.
// **읽을 수 있는 말은 SD 에 들어 있는 것뿐**이라 세 묶음을 굽는다:
//   · 고정 문구 — 화면에 그대로 뜨는 안내문(폴더 01)
//   · 0~100     — 한 토막씩 통째로(폴더 03). 소리로 나가는 수는 거의 다 여기다
//   · 숫자 토막 — 이~구·백·천·만(폴더 02). 100 을 넘는 잔액의 **앞자리**에만 쓴다 —
//                 끝 두 자리는 폴더 03 에서 통째로 가져온다(125 → 백 + 이십오)
// 화면에 뜨는 글자 가운데 **'지금 기분'·서버가 보낸 거절 안내**는 못 읽는다 —
// 교회 설정과 아이가 쓴 글에 딸려 바뀌어 미리 구울 수가 없다. 그 자리는 조용히 지나간다
// (아래 '다음 걸음' 참고). **아이 이름**은 서버가 만들어 준 것을 기기가 받아 SD 에 써 두고
// 태깅 때 맨 앞에 읽는다(/09 · NAME_VOICE.md).
// ★ 표·번호·대본은 v1(DFPlayer 판)과 같다. 다른 것은 파일 꼴(.mp3 → .wav)과 그것을 트는 쪽뿐 —
//   이 헤더의 함수들은 v1 과 모양이 같아 main.cpp 는 그대로 부른다.
//
// ── 읽는 말 = 화면 글자 ──────────────────────────────────────────
// 토막의 대본은 **화면에 뜨는 글자와 같게** 둔다. 두 가지를 얻는다:
//   · 안내문 한 줄만 보고 어느 토막을 틀지 고를 수 있다(soundSayNote 의 표) — 부르는
//     곳마다 소리 번호를 따로 들고 다니지 않아도 되고, 서버(허브)가 밀어 준 안내문도
//     같은 길로 읽힌다.
//   · 나중에 서버가 합성해 보내 주게 되면 **서버가 보낸 글자를 그대로** 읽으면 된다.
// 어쩔 수 없이 다른 데가 두 곳이다 — 'PN532' 는 소리로 읽을 말이 아니라 '리더' 로,
// 'WiFi' 는 '와이파이' 로 굽는다. 그 둘은 아래 표의 주석에 적어 두었다.
//
// ── SD 카드 ──────────────────────────────────────────────────────
// 폴더 두 자리 · 파일 세 자리다(v1 의 DFPlayer 짜임새를 그대로 — 번호를 고르는 코드가 같다).
//   /01/001.wav … /01/013.wav   고정 문구 (아래 SndClip 과 번호가 같다)
//   /02/001.wav … /02/014.wav   숫자 토막 (영·일~구·십·백·천·만) — 100 초과의 앞자리용
//                               (영·일·십 은 쓰이지 않는다. 번호 자리만 지킨다)
//   /03/001.wav … /03/101.wav   0~100 통째 (번호 = 수 + 1)
//   /voice.ver                  고정 토막이 서버의 어느 판인가(5단계 — 기기가 받아 갈아 끼운다)
//   /09/<키 8자>.wav            아이 이름 — **기기가 스스로 받아 쓴다**(손으로 넣지 않는다 ·
//                               폴더도 없으면 만든다). 아래 '이름 소리' · NAME_VOICE.md
// WAV 는 PCM 16비트 · 모노 · 22050Hz 다(tools/make_voices.sh — 맥의 say -v Yuna + ffmpeg).
// 다른 표본율·스테레오도 읽기는 한다(앰프를 그 율로 바꿔 틀고, 스테레오는 섞는다).
// ★ mp3 가 아니라 WAV 인 까닭: 풀어 줄 디코더가 필요 없고(코어의 SD · ESP_I2S 만으로 된다),
//   토막이 1초 남짓이라 크기(한 토막 40KB 쯤 · 전부 6MB 쯤)가 문제 되지 않는다.
// 번호를 바꾸면 **여기와 그 스크립트를 함께** 고칠 것 — 둘이 어긋나면 엉뚱한 말이 나온다.
// FAT32 로 포맷하고, 폴더 이름은 꼭 두 자리('1' 이 아니라 '01')로 둔다.
//
// ── 어디서 소리가 나나 ───────────────────────────────────────────
//   태깅        showNfc() 가 안내문 한 줄을 넘긴다 → soundSayNote()
//   부팅        '리더 준비 중' · '와이파이 붙는 중' (SOUND_SAY_BOOT)
//   치명        PN532 를 못 찾았을 때 (그 자리에서 기기가 서므로 soundPump 로 돌린다)
//   버튼 길게   '설정 다시 받는 중'
//   시리얼 'v'  토막을 하나씩 차례로 — 스피커·SD·번호를 눈이 아니라 귀로 확인한다
//   시리얼 'a'  이름표의 아이 이름 소리를 하나씩 차례로
//
// ── 다음 걸음 — 서버가 합성해 보내 주기 ─────────────────────────
// 아이 이름은 그 길로 들어왔다 — 서버가 합성한 WAV 를 받아 /09/<키>.wav 에 써 두고 같은
// 일꾼으로 튼다. 서버의 거절 안내('화요일은 출석을 안 받아요')도 같은 길로 갈 수 있다.
// 갈아 끼울 자리는 soundSayNote() 아래쪽('모르는 안내문') 하나다.
// 어느 길로 가든 **읽을 글자를 고르는 곳은 soundSayNote() 하나**로 둔다.
// ─────────────────────────────────────────────────────────────────

#include <Arduino.h>

#include "config.h"

// 폴더 01 — 고정 문구. 번호가 곧 /01/NNN.wav 다.
// ★ tools/make_voices.sh 의 표와 번호·대본이 같아야 한다.
enum SndClip : uint8_t {
  SND_NONE = 0,
  SND_IDLE_PROMPT = 1,   // 카드를 올려 주세요
  SND_BALANCE = 2,       // 잔여 포인트
  SND_ALREADY = 3,       // 이미 출석했어요
  SND_UNKNOWN_CARD = 4,  // 등록되지 않은 키링
  SND_NO_SERVER = 5,     // 서버에 물어보지 못했어요
  SND_CONFIG = 6,        // 설정 다시 받는 중
  SND_READER_INIT = 7,   // 리더 준비 중      (화면은 'PN532 준비 중')
  SND_WIFI = 8,          // 와이파이 붙는 중  (화면은 'WiFi 붙는 중')
  SND_READER_FAIL = 9,   // 리더를 찾을 수 없어요 (화면은 'PN532 · 찾을 수 없음')
  SND_ATTEND_OK = 10,    // 출석 완료   — 뒤에 숫자와 '포인트' 가 붙는다
  SND_POINT = 11,        // 포인트
  SND_ETC = 12,          // 외          — '외 N명'
  SND_PEOPLE = 13,       // 명
};

// 켤 때 한 번. SD 를 붙이고(HSPI) 앰프(I2S)를 켜고 재생 일꾼(태스크)을 세운다.
// 실패해도 기기는 선다 — 소리만 조용하다(soundReport 가 까닭을 찍는다).
void soundBegin();

// 본 고리에서 매번 — v2 는 재생을 일꾼이 맡아 할 일이 없다. v1 과 부르는 꼴을 맞추려고 둔다.
void soundLoop();

// loop 가 아직 안 도는 자리(setup·치명 화면)에서 쉰다 — 일꾼이 따로 돌아 그동안에도 읽힌다.
void soundPump(uint32_t ms);

// 고정 토막 하나를 읽는다. 읽고 있던 것은 끊는다 — 앞 아이의 잔액을 뒷 아이 앞에서
// 계속 읽고 있으면 안 된다.
void soundSay(uint8_t clip);

// 끊지 않고 **줄 뒤에 이어 세운다.** 부팅 안내처럼 두 토막이 차례로 읽혀야 하는 자리에
// 쓴다 — soundSay() 로 두 번 부르면 줄을 비우므로 앞의 것이 버려진다. setup 은
// soundLoop() 을 돌리지 않아(화면·리더·와이파이가 먼저다) 그 사이에 읽히지도 않는다.
void soundSayMore(uint8_t clip);

// 화면에 뜬 안내문 한 줄을 읽는다. 아는 문구면 토막을 이어 붙이고, 모르는 문구(서버가
// 보낸 거절 안내)면 조용히 지나간다. note 가 비어 있으면 잔액을 읽는다.
// nameKey(이름표의 snd)가 있고 그 소리가 SD 에 있으면 **이름부터** 읽는다(SOUND_SAY_NAME).
// 없으면 이름만 건너뛴다 — 아직 못 받은 아이·미등록 키링은 지금처럼 안내문만.
//   "출석 완료 +5P" + 키 → [김하은][출석 완료][오][포인트]
//   "출석 완료 +5P" → [출석 완료][오][포인트]
//   ""              → [잔여 포인트][오십칠]          잔액이 100 까지면 한 토막
//   ""              → [잔여 포인트][백][이십오]       넘으면 앞자리만 세우고 끝 두 자리는 통째로
//   ""              → [잔여 포인트][천][이][백][오]
void soundSayNote(const char *note, long points, const char *nameKey = nullptr);

// 읽던 것을 끊고 줄도 비운다.
void soundStop();

// 소리 크기 0~30.
void soundVolume(uint8_t vol);

// ── 아이 이름 소리 (/09/<키 8자>.wav) ────────────────────────────
// 서버가 만든 이름 소리를 본 고리가 받아 오고, **SD 에 쓰는 것은 재생 일꾼**이 한다(SD 는
// 일꾼만 만진다). 일꾼은 켤 때 /09 를 한 번 훑어 있는 키 목록을 들고 있다 — 본 고리는 SD 를
// 건드리지 않고 그 목록만 본다. 절차 전체는 NAME_VOICE.md.

// 일꾼이 /09 를 다 훑었고 SD 가 붙어 있다 — 그 전에는 받으러 가지 않는다.
bool soundNamesReady();

// 그 키의 소리가 SD 에 있다.
bool soundHasName(const char *key);

// 받은 WAV 가 일꾼이 틀 수 있는 꼴인지(RIFF · PCM 16비트 · 1~2채널). 쓰기 전에 본다.
bool soundWavOk(const uint8_t *buf, size_t len);

// 받은 WAV 를 일꾼에게 넘긴다 — **buf 는 일꾼 것이 된다**(다 쓰면 free 한다).
// 앞의 것을 아직 쓰는 중이거나 SD 가 없으면 false — 그때는 부른 쪽이 free 한다.
bool soundStoreName(const char *key, uint8_t *buf, size_t len);

// 앞에 넘긴 것을 아직 쓰는 중이다.
bool soundStoreBusy();

// ── 고정 토막 판 (5단계 — 서버가 같은 목소리로 만든 /01 · /02 · /03) ──
// 받은 토막을 /NN/NNN.wav 자리에 갈아 끼운다(쓰는 길은 이름 소리와 같다 — buf 는 일꾼 것이 된다).
bool soundStoreClip(uint8_t folder, uint8_t track, uint8_t *buf, size_t len);
// /voice.ver 에 판 이름(16진 8자)을 쓴다. 빈 값이면 지운다 — 판을 받기 시작할 때 먼저 지워 두어,
// 다 받기 전에 끊겨도 '같은 판' 으로 보이지 않게.
bool soundStorePackVer(const char *ver);
// SD 의 판 이름(없으면 빈 값). 맥 스크립트로 넣은 카드는 파일이 없다.
void soundPackVer(char *out, size_t n);

// 이름 소리 하나만 읽는다(시리얼 'a'). 읽던 것은 끊는다. SD 에 없으면 false.
bool soundSayName(const char *key);

// 시리얼 'v' — 토막을 하나씩 차례로 읽어 본다.
void soundTestNext();

// 시리얼 'i' — 지금 상태 한 줄.
void soundReport();
