// 줄을 선 아이가 두 번 대거나, 대고 있는 동안 리더가 여러 번 읽어도 포인트가 겹치지 않게.
// 기기에 시계(RTC)가 없어 "하루 한 번" 을 알 수 없다 — 시간 간격으로 막는다.
#define ATTEND_COOLDOWN_MS 600000UL     // 10분
