// master(화면) + slave(리더) 를 한 보드에 합친 것이다 — 리더가 선·라디오로 오지 않고,
// PN532 가 이 보드의 I2C 버스에 바로 붙는다.

// ── 인증정보는 여기 없다 ──────────────────────────────────────────
// 와이파이(SSID·비밀번호 네 벌)와 펀펀포인트 기기 키는 세 프로젝트가 함께 보는
// secrets/ChurchSecrets.h 에 있다. **그 파일은 깃에 올라가지 않는다**(.gitignore) —
// 기기 키가 새면 그 교회의 포인트를 올릴 수 있어서다.
//
// 받아 간 뒤 한 번:  cp secrets/ChurchSecrets.example.h secrets/ChurchSecrets.h
// 들어오는 길은 platformio.ini 의 build_flags = -I ... 다(없으면 여기서 멈춘다).
#include <ChurchSecrets.h>

// ── mDNS ──────────────────────────────────────────────────────────
// 붙은 뒤 http/ws 로 이 이름으로 찾을 수 있다: nfc-display.local
// (같은 망의 PC·폰에서 IP 를 몰라도 이 이름으로 접속된다)
#define MDNS_HOSTNAME "nfc-display"

// ── WebSocket 서버 포트 ───────────────────────────────────────────
// 외부(NFC 시스템)가 여기에 붙어 화면 상태를 보낸다: ws://nfc-display.local:81/
#define WS_PORT       81

// ── PN532 리더 (이 보드의 I2C 버스에 직접) ────────────────────────
// 예전에는 ESP32-C3(slave)가 PN532 를 읽어 선(I2C)이나 라디오(ESP-NOW)로 UID 를 넘겼다.
// 이제 **그 보드가 없다** — PN532 를 이 화면 보드에 바로 물린다. 그래서 config.h 에서
// LINK_I2C_*·ESPNOW_* 설정이 모두 사라졌고, 선이 죽어 라디오로 넘어가는 길도 없다.
// 한 보드가 카드를 읽고, 서버에 묻고, 화면을 그리고, 소리를 낸다.
//
// **왜 SPI 가 아니라 I2C 인가** — 이 보드에 남는 GPIO 가 없다. 라일리고 공식 문서가
// 그대로 적어 두었다: "The Grove port has been set to I2C, sharing the bus with the touch
// and cannot be used for other purposes" / "T-RGB has no free GPIO and cannot be expanded".
// RGB 패널이 2·3·5·6·7·9~18·21·41·42·45·47 을, OPI PSRAM 이 35~37 을, microSD 가 38~40 을,
// 백라이트가 46 을, USB 가 19·20 을 먹는다. 1 은 터치 INT, 4 는 배터리 전압,
// 43·44 는 UART0 라 바깥 커넥터에 나오지 않는다. **밖으로 나온 GPIO 는 Grove 4핀의
// GPIO8(SDA)·GPIO48(SCL) 둘뿐이고 그것도 이미 I2C 다** — SPI 넉 선을 뽑을 자리가 없다.
// 그래서 PN532 를 그 버스에 함께 태운다(주소 0x24). 터치 0x15·확장칩 XL9535 0x20 과
// 겹치지 않고, 풀업도 이 보드에 이미 있다. 선 세 가닥만 꽂으면 끝이고 납땜이 없다.
//
//   Grove 4핀 커넥터        PN532 모듈
//     3V3   ───────────      VCC
//     GND   ───────────      GND
//     GPIO8 (SDA) ─────      SDA
//     GPIO48(SCL) ─────      SCL
//
// ★ **모듈 딥스위치를 I2C 로 놓아야 한다** (Elechouse V3 는 보통 1:ON 2:OFF — 보드 뒷면
//   표로 확인). SPI 로 두면 SDA 가 조용해 PN532 를 못 찾는다.
// ★ PN532 VCC·GND 바로 옆에 100µF 전해 + 0.1µF 세라믹을 병렬로 — 없으면 태그 순간 리셋된다.
//
// ※ 2026-09-24 에 쓰던 모듈은 I2C 쪽(SCL)이 고장 나 SPI 로 돌렸던 적이 있다(slave 머리말).
//   그 모듈로는 이 배선이 안 된다 — 멀쩡한 모듈이어야 한다. PN532 를 못 찾으면 코드가
//   5초마다 다시 찾아보며 시리얼에 배선·딥스위치를 확인하라고 찍는다.
#define PN532_I2C_ADDR 0x24     // 라이브러리 고정값(PN532_I2C_ADDRESS) — 참고용으로 적어 둔다
// IRQ·RSTPD_N 은 **잇지 않는다**(남는 핀이 없다). 라이브러리에 255 를 넘기면 그 둘을
// 쓰지 않는 길로 돈다 — 준비 여부를 I2C 로 읽어 보고, 하드웨어 리셋은 건너뛴다.
#define PN532_NO_PIN  255

// ── 패시브(수동) 스피커 ───────────────────────────────────────────
// 소리는 **GPIO0 한 가닥**으로 낸다. 위에 적은 대로 밖으로 나온 핀이 없어서, 이 한 핀만은
// 보드의 **BOOT 버튼 패드에 납땜**해 뽑아야 한다(버튼 한쪽이 GPIO0, 다른 쪽이 GND 다).
//
//   GPIO0 (BOOT 패드) ──── 스피커(+)
//   GND               ──── 스피커(−)
//
// 왜 GPIO0 인가 — 남은 자리 중에 **출력으로 써도 괜찮은 유일한 핀**이다. GPIO1 은 터치칩이
// 제 손으로 끌어내리는 INT 선이라 우리가 밀면 서로 싸우고, GPIO4 는 배터리 전압 분압에
// 물려 있고, 43·44 는 커넥터에 나오지 않는다. GPIO0 은 부팅 모드를 정하는 스트래핑 핀이지만
// 그것을 보는 것은 **부팅하는 순간**뿐이라, 부팅 뒤에 출력으로 쓰는 것은 괜찮다.
// (굽는 동안 BOOT 를 누르면 그 순간 출력이 GND 로 눌린다 — 굽는 중에는 소리를 안 내니 탈이 없다.
//  스피커가 GPIO0 을 LOW 로 당기지 않게 **직렬로 100Ω** 을 두는 쪽이 안전하다. 안 그러면
//  코일 저항이 낮아 부팅 때 BOOT 를 누른 것처럼 보일 수 있다.)
//
//   삑(높게 한 번)       서버가 아는 키링으로 처리했다
//   삐-삐(낮게 두 번)    서버에 없는 카드 · 서버에 못 물었다
//   삐리(올라가는 두 음) 켜져서 PN532 가 준비됐다
#define PIN_BUZZER   0
#define BUZZER_ACTIVE 0         // 0 = 수동(패시브) 스피커 — 음 높이를 낸다 / 1 = 능동(액티브) 부저 — 켜고 끄기만

// ── NFC 폴링 ──────────────────────────────────────────────────────
// 훑는 순간마다 PN532 가 RF 필드를 켜 전류를 쓴다 — 쉬는 시간이 그대로 모듈 발열로 이어진다.
// 120ms 면 사람이 카드를 대고 있는 시간(보통 0.5초 넘는다)보다 훨씬 짧아 놓치지 않는다.
// (slave 에 있던 CPU_MHZ 는 가져오지 않았다 — 이 보드는 RGB 패널을 돌려야 해서 240MHz 가 필요하다)
#define NFC_POLL_EVERY_MS  120   // 폴링 사이 쉬는 시간. 0 이면 쉬지 않는다
#define NFC_RETRIES       0x05   // 한 번 훑는 길이. 짧을수록 RF 켜는 시간이 줄어든다

// ── 같은 카드 연속 처리 방지 ──────────────────────────────────────
// 카드를 대고 있는 동안 같은 UID 가 계속 읽힌다. 이 시간 안의 같은 UID 는 한 번으로 친다.
// (출석이 겹치는 것은 ATTEND_COOLDOWN_MS 가 따로 막는다 — 이쪽은 '대고 있는 동안' 을 막는 자다)
#define SAME_TAG_COOLDOWN_MS 3000

// ── 펀펀포인트 서버 (사진 다운로드) ───────────────────────────────
// 화면을 길게 누르면 이 서버의 이름표(roster)를 받아, 사진이 있는 UID 마다
// 480 원형 사진(RGB565)을 내려받아 microSD 에 /talent/<UID>.565 로 저장한다.
// 그다음 NFC 태그가 오면 SD 에서 그 UID 사진을 읽어 화면에 띄운다.
//   운영: "https://funfun.youthvision.co.kr"   개발: "http://192.168.0.10:8200" (자기 PC IP)
//
// ★ 2026-10-11 에 yvServer(youthvision.co.kr) → funfunServer 로 옮겼다(전환 Phase 8).
//   두 서버는 **RTDB 가 갈려 있다** — 잔액·명단의 원본이 서로 다른 DB 에 있다.
//   그래서 이 한 줄을 바꾸는 것은 '주소를 바꾸는 일' 이 아니라 **기기가 보는 자료를
//   통째로 바꾸는 일**이다. 저쪽에만 있는 아이는 그 자리에서 '등록되지 않은 키링' 이 된다.
//   되돌리려면 이 줄을 youthvision.co.kr 로 돌리고 다시 구우면 된다(기기 키는 양쪽이 같다).
