// nfcProjectClient 설정 — 이 파일만 고치면 된다(코드는 건드리지 않는다).

// ── 디스플레이와 선 없이 잇기 (ESP-NOW) — 2순위 길 ────────────────
// 2026-10-11 에 **와이파이/WebSocket 을 걷어내고 ESP-NOW 로 바꿨다.**
//
// 예전 2순위는 이랬다: 공유기에 붙고(수 초) → mDNS 로 nfc-display.local 을 찾고(들쭉날쭉,
// 막힌 공유기면 고정 IP 를 손으로) → ws://<IP>:81/ 에 접속. 공유기가 죽으면 그 길도 함께
// 죽었다. ESP-NOW 는 공유기를 아예 거치지 않는다 — 두 보드가 라디오로 바로 말한다.
// 왕복이 수 ms 고, 공유기가 꺼져 있어도 태깅이 된다. **이 리더는 이제 어느 와이파이에도
// 붙지 않는다** — 그래서 SSID·비밀번호·mDNS·디스플레이 IP 설정이 모두 없어졌다.
//
// 오가는 글자는 선(I2C)과 **똑같은 JSON** 이다. 규약이 하나라 푸는 곳도 하나다.
//
// ★ **채널을 이쪽이 찾아간다.** ESP-NOW 는 두 보드가 같은 와이파이 채널에 있어야 하는데,
//   디스플레이는 공유기에 붙어 있어 채널을 제가 고르지 못한다(공유기가 정한다).
//   그래서 이 리더가 1~13 을 돌며 "거기 있니" 를 부르고, 디스플레이가 답하면 그 채널에
//   자리 잡는다. 공유기가 채널을 바꾸면 조용해지고, 그러면 다시 찾아 나선다. 손댈 것은 없다.
//
// ★ 짝은 저절로 맺힌다 — MAC 주소를 적어 둘 필요가 없다.
#define ESPNOW_ENABLE 1          // 0 = 선(I2C)만 쓴다(선이 빠지면 태깅이 안 된다)

// 우리 둘만 알아듣는 표식. **디스플레이(master/src/config.h)의 같은 값과 같아야 한다.**
// 자물쇠가 아니라 이름표다 — 같은 채널의 남의 ESP-NOW 기기와 헷갈리지 않게 하는 것뿐이다.
#define ESPNOW_MAGIC "FFP1"

// 한 채널에 머무르며 불러 보는 시간. 디스플레이는 사진을 받거나 서버에 묻는 동안 loop 가
// 수백 ms 늦어지는데, 그 사이에 답이 오면 이미 다음 채널로 옮겨 가 놓친다 — 넉넉히 둔다.
// 흔한 채널(1·6·11)을 먼저 돌므로 보통은 1초 안에 찾는다(main.cpp 의 HUNT_ORDER).
#define ESPNOW_HUNT_MS    400
#define ESPNOW_CH_MAX      13    // 쓸 수 있는 가장 높은 채널(한국·유럽 13, 미국 11, 일본 14)
#define ESPNOW_PING_MS   3000    // 자리 잡은 뒤에도 이 주기로 안부를 묻는다(채널이 바뀌면 알아채려고)
#define ESPNOW_ALIVE_MS 10000    // 이 시간 안에 답이 없으면 자리를 뜨고 다시 찾아 나선다

// ── 디스플레이와 직접 잇는 선 (I2C 슬레이브) ──────────────────────
// 두 보드를 선으로 이으면 와이파이·공유기·mDNS 를 거치지 않는다 — 망이 죽어도 태깅이
// 되고, 왕복이 500ms 에서 수 ms 로 줄고, 라디오를 안 켜서 C3 가 시원하다.
//
// **왜 UART 가 아니라 I2C 인가** — 디스플레이(LILYGO T-RGB)가 밖으로 내주는 건 옆면
// 1.25mm 4핀 커넥터 하나뿐이고, 그 넉 선은 3V3·GND·GPIO8(SDA)·GPIO48(SCL) 이다.
// RGB 패널이 나머지 핀을 거의 다 먹어 UART 로 쓸 핀이 남지 않는다(43·44 는 커넥터에
// 나오지 않고, 1 은 터치 INT, 4 는 배터리 전압 측정이다). 그래서 그 커넥터가 원래
// 하려던 대로 I2C 로 붙는다 — 이 리더가 그 버스의 **슬레이브**가 된다.
//
//   T-RGB 4핀 커넥터        이 리더(C3)
//     GND    ───────────     GND        ← 필수
//     GPIO8  (SDA) ──────    GPIO20 (SDA)
//     GPIO48 (SCL) ──────    GPIO21 (SCL)
//     3V3    ── 잇지 마라 ── (C3 는 자기 USB 로 먹인다)
//
// **3V3 은 잇지 않는다.** C3 를 USB 로도 먹이면서 이 선까지 이으면 두 레귤레이터가
// 맞물린다. C3 를 USB 없이 쓸 때만 3V3 을 잇고, 그때는 USB 를 뽑아라.
// 풀업 저항은 T-RGB 쪽에 이미 있다(터치·확장칩이 쓰는 버스다) — 더 달지 않는다.
//
// 슬레이브는 먼저 말을 걸 수 없다. 그래서 읽은 UID 를 칸에 적어 두면, 디스플레이가
// LINK_POLL_MS 마다 "줄 것 있나" 하고 가져간다. 결과는 반대로 저쪽이 써 넣어 준다.
//
// 이 버스에는 **화면 확장칩(XL9535)과 터치도 함께** 붙어 있다. 슬레이브 콜백에서
// 꾸물거리면 화면이 멈춘다 — 콜백 안에서는 메모리 복사만 하고, 처리는 loop 에서 한다.
//
// 선과 와이파이는 **함께 산다** — 선이 살아 있으면 선으로만 보내고, 선이 조용해지면
// (케이블이 빠졌거나 디스플레이가 꺼졌다) 그때 와이파이를 켜서 WebSocket 으로 붙는다.
// 한 태깅은 언제나 한 경로로만 나간다 — 두 경로로 보내면 출석이 두 번 올라간다.
#define LINK_I2C_ENABLE      1     // 0 = 선을 안 쓴다(예전처럼 와이파이만)
#define PIN_LINK_SDA        20     // SPI(4~7)·부저(10)·스트래핑(2·8·9)·USB(18·19)를 피한 자리
#define PIN_LINK_SCL        21
#define LINK_I2C_ADDR     0x30     // 버스에 이미 있는 0x15(터치)·0x20(확장칩)·0x24(PN532)와 안 겹친다
#define LINK_I2C_HZ     400000     // 디스플레이(마스터)의 Wire.begin 과 같은 값
#define LINK_ALIVE_MS     3000     // 이 시간 안에 마스터가 말을 걸었으면 선이 살아 있다고 본다
#define LINK_WIFI_FALLBACK   1     // 1 = 선이 죽으면 와이파이로 넘어간다 / 0 = 선만 쓴다
#define LINK_GRACE_MS     8000     // 선이 이만큼 조용하면 그제서야 와이파이를 켠다

// ── 디스플레이의 답을 기다리는 시간 ───────────────────────────────
// UID 를 넘기면 디스플레이가 서버에 물어(출석모드면 지급까지 하고) 결과를 돌려준다.
// 이 시간 안에 답이 없으면 실패음을 낸다 — 소리가 없으면 자원봉사자는 못 읽은 줄 알고 또 댄다.
#define ACK_WAIT_MS 4000

// 펀펀포인트 서버 주소·기기 키는 이제 여기에 없다.
// 서버와 이야기하는 쪽은 디스플레이(nfcProject) 하나다 — 이 리더는 UID 만 넘긴다.

// ── PN532 (SPI) 배선 ────────────────────────────────────────────────
//   3V3→VCC · GND→GND
//   GPIO4→SCK · GPIO5→MISO · GPIO6→MOSI · GPIO7→SS(NSS)
//   **모듈 딥스위치를 SPI 로 놓아야 한다** (Elechouse V3 는 보통 1:OFF 2:ON —
//   보드 뒷면 표로 확인). I2C 로 두면 MISO 가 조용해 아무것도 안 읽힌다.
//
//   왜 I2C 가 아니라 SPI 인가 — 2026-09-24 실기에서 이 모듈의 I2C 쪽(SCL)이
//   고장 난 것을 확인했다. 같은 모듈이 SPI 로는 v1.6 으로 멀쩡히 응답하고
//   145초 소크에서 감시 실패 0·재초기화 0 이었다. 전원은 결백하다.
//
//   C3 기본 SPI 핀이 마침 4·5·6·7 이라 I2C 때 쓰던 GPIO4·5 를 그대로 쓴다.
//   GPIO8·9 는 부팅 스트래핑 핀이라 쓰지 않는다.
#define PIN_NFC_SCK   4
#define PIN_NFC_MISO  5
#define PIN_NFC_MOSI  6
#define PIN_NFC_SS    7

// ── 부저 ──────────────────────────────────────────────────────────
// C3 에는 화면이 없어 소리로 알린다.  GPIO10 → 부저(+) · GND → 부저(−)
// **GPIO7 에서 옮겨 왔다** — SPI 의 SS 가 GPIO7 을 쓰기 때문이다. 선을 옮겨 꽂아야 한다.
// GPIO2·8·9 는 스트래핑, 18·19 는 USB, 20·21 은 UART 라 피했다. -1 이면 소리를 끈다.
#define PIN_BUZZER   10
#define BUZZER_ACTIVE 0                // 0 = 수동(패시브) 부저 — 음 높이를 낸다 / 1 = 능동(액티브) 부저 — 켜고 끄기만

// ── 발열 줄이기 ───────────────────────────────────────────────────
// 셋 다 "조금 느려지는 대신 시원해지는" 맞바꿈이다. 더 시원하게 하려면 숫자를
// 키우고(POLL_EVERY_MS), 반응이 굼뜨면 줄인다. 시리얼 `cpu`·`poll`·`rty` 로
// 구운 채로도 바꿔 보고 정할 수 있다.
//
// 열이 어디서 나는지부터 보라 —
//   C3 가 뜨겁다     → 라디오다. 선이 빠져 ESP-NOW 로 넘어간 뒤에만 올라온다(radioGate)
//   PN532 이 뜨겁다  → NFC_POLL_EVERY_MS 다. 훑는 순간마다 RF 필드를 켜서 전류를 쓴다
#define CPU_MHZ             80   // 160 → 80. USB CDC 가 도는 최저다. 그 아래는 시리얼이 끊긴다
#define NFC_POLL_EVERY_MS  120   // 폴링 사이 쉬는 시간. 0 이면 쉬지 않는다(예전 동작)
#define NFC_RETRIES       0x05   // 한 번 훑는 길이. 0x10 → 0x05 로 RF 켜는 시간을 줄인다
// 라디오 재우기(WIFI_MODEM_SLEEP)는 없앴다 — ESP-NOW 는 공유기에 붙지 않아 깨어날 약속
// (DTIM)이 없다. 재우면 받는 쪽이 덩이를 놓친다. 대신 **선이 살아 있는 동안은 라디오를
// 아예 올리지 않으므로**(radioGate), 평소 자리에서는 예전보다 오히려 시원하다.

// ── 같은 카드 연속 처리 방지 ──────────────────────────────────────
// 카드를 대고 있는 동안 같은 UID 가 계속 읽힌다. 이 시간 안의 같은 UID 는 한 번으로 친다.
#define SAME_TAG_COOLDOWN_MS 3000

// ── 소리 (DFPlayer Mini · YX5200) — 2026-10-21 ─────────────────────
// 미리 구워 둔 한국어 토막을 이어 읽는다. 합성은 하지 않는다 — 이 모듈이 하는 일은
// 제 microSD 에 든 mp3 를 **번호로 틀어 주는 것**뿐이다. 무엇을 읽고 무엇을 못 읽는지,
// SD 를 어떻게 꾸미는지는 src/sound.h 머리말에 있다.
//
// **왜 디스플레이가 아니라 이 리더에 붙나** — DFPlayer 는 UART 로만 말을 듣는데,
// 디스플레이(T-RGB)가 밖으로 내주는 것은 저 위에 적은 4핀 커넥터(I2C) 하나뿐이다.
// 저쪽에 달려면 I2C→UART 다리칩을 끼워야 하지만, 이 보드에는 쓰지 않는 핀이 그냥
// 남아 있다. 덤으로 스피커가 아이가 카드를 대는 자리에 온다.
// 읽을 말은 디스플레이가 글자로 보내 준다(태깅 답의 note·points, 또는 {"say":"…"}).
//
// 0 으로 두면 소리 쪽이 통째로 빠진다(UART 도 열지 않는다) — 모듈을 안 달고 구울 때.
#define SOUND_ENABLE 1

// UART1. 쓰고 있는 핀을 피했다 — PN532(SPI)가 4·5·6·7, 부저가 10, 선(I2C)이 20·21,
// USB 가 18·19, 2·8·9 는 부팅 스트래핑이다. 남은 0·1·3 에서 둘을 쓴다(3 은 남겨 둔다).
// ★ DF_TX 는 **모듈의 RX** 로 간다(이름이 엇갈리니 배선할 때 조심). 모듈은 5V 로
//   돌지만 입력은 3.3V 를 알아듣는다 — 다만 모듈 RX 에 1kΩ 을 끼우는 것이 통례다
//   (전압을 낮추려는 것이 아니라 그 선이 잡음을 타 엉뚱한 명령으로 읽히는 것을 막는다).
// ★ RX 를 꼭 잇는다. 다 읽었다는 알림(0x3D)으로 다음 토막을 밀어 넣기 때문이다 —
//   안 이으면 토막마다 빗장 시간(5초)을 기다려 말이 뚝뚝 끊긴다.
#define DF_TX_PIN 0   // C3 TX → 모듈 RX (1kΩ 직렬)
#define DF_RX_PIN 1   // C3 RX ← 모듈 TX
// 배선: VCC=5V · GND=GND · SPK_1/SPK_2 에 3W 꼬마 스피커(또는 DAC_L/DAC_R 를 앰프로)
//      BUSY 는 쓰지 않는다 — 다 읽었다는 것은 모듈이 UART 로 알려 준다(0x3D).
// ★ 5V 는 C3 의 USB 핀(5V)에서 끌어온다. 소리가 날 때 전류가 확 뛰므로 모듈 VCC 바로
//   옆에 100µF 를 하나 달아라 — 없으면 큰 소리에서 C3 가 리셋되는 일이 있다.

// 소리 크기 0~30. 교회 로비에서 22 쯤이 적당했다.
#define SOUND_VOLUME 22

// 토막과 토막 사이 쉼. 0 으로 두면 숫자가 뭉개져 들린다.
#define SOUND_GAP_MS 60

// 켜질 때 "리더 준비 중" 을 읽는다 — 상자가 살아 있다는 신호.
// (디스플레이 쪽 사정인 "와이파이 붙는 중" 은 저쪽이 선으로 보내 준다)
#define SOUND_SAY_BOOT 1

// 그냥 조회(출석모드가 아닐 때)에서 잔액까지 읽는다.
#define SOUND_SAY_BALANCE 1

// 부저(삑·삐-삐)를 말과 함께 쓴다. 말보다 빨라 '읽혔다' 를 먼저 알려 준다 —
// 까닭은 sound.h 의 '부저는 그대로 둔다'. 0 으로 두면 말만 한다.
#define SOUND_KEEP_BEEP 1

// 같은 답이 잇달아 와도 이 시간 안에는 다시 읽지 않는다. 디스플레이는 상태가 바뀔
// 때마다 알림을 보내므로, 한 태깅에 같은 덩이가 두 번 올 수 있다.
#define SOUND_REPEAT_MS 3000
