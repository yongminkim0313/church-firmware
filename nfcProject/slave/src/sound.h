#pragma once
// ─────────────────────────────────────────────────────────────────
// 소리 — 미리 구워 둔 토막을 이어 읽는다 (DFPlayer Mini · YX5200)
//
// funfunFirmware/src/sound.{h,cpp} 를 옮겨 온 것이다. 하는 일도, SD 짜임새도,
// 번호도 **그 쪽과 같다** — 카드 한 장을 두 기기에 돌려 쓸 수 있게 일부러 맞췄다.
// 다른 데는 둘이다: ① 모듈이 디스플레이가 아니라 **이 리더**에 붙는다 ② 읽을 말을
// 번호가 아니라 **글자로 건네받는다**. 까닭은 바로 아래.
//
// ── 왜 디스플레이가 아니라 리더에 붙나 ───────────────────────────
// DFPlayer 는 UART 로만 말을 듣는다. 그런데 디스플레이(LILYGO T-RGB)가 밖으로
// 내주는 것은 옆면 1.25mm 4핀 커넥터 하나뿐이고, 그 넉 선은 3V3·GND·GPIO8(SDA)·
// GPIO48(SCL) — **I2C 다**. RGB 패널·SD·PSRAM 이 나머지 핀을 다 먹어 UART 로 낼 핀이
// 남지 않는다(config.h 의 배선 설명과 같은 이야기다). 그래서 소리를 저쪽에 달려면
// I2C→UART 다리칩을 하나 더 끼워야 하는데, **이 리더(C3)에는 쓰지 않는 핀이 그냥 남아
// 있다**(GPIO0·1·3). 부품을 늘리지 않는 쪽을 골랐다.
// 덤도 있다 — 스피커가 아이가 카드를 대는 자리에 온다. 소리는 그 아이에게 하는 말이다.
//
// ── 읽을 말은 어디서 오나 ────────────────────────────────────────
// 이 리더는 서버와 말하지 않는다(main.cpp 머리말). 이름·잔액·출석 여부는 모두
// 디스플레이가 알아내 **글자로** 돌려준다 — 태깅 답으로 오는
//   {"uid":…,"name":…,"points":57,"known":true,"note":"출석 완료 +5P"}
// 그 note 와 points 를 그대로 soundSayNote() 에 넘기면 된다. 규약을 늘리지 않았다 —
// 이 답은 소리를 달기 전부터 오가고 있었다(삑/삐-삐 를 가르는 데 쓰던 바로 그 덩이다).
// 디스플레이 제 쪽에서 일어난 일('설정 다시 받는 중' 따위)은 {"say":"<문구>"} 로 온다.
// 어느 쪽이든 **글자**다. 그래서 번호를 고르는 곳은 soundSayNote() 하나다.
//
// ── 읽을 수 있는 말 ──────────────────────────────────────────────
// 이 모듈은 합성을 하지 않는다. 제 microSD 에 든 mp3 를 번호로 틀어 주는 것뿐이라,
// **읽을 수 있는 말은 SD 에 들어 있는 것뿐**이다. 세 묶음을 굽는다:
//   · 고정 문구 — 화면에 그대로 뜨는 안내문(폴더 01)
//   · 0~100     — 한 토막씩 통째로(폴더 03). 소리로 나가는 수는 거의 다 여기다
//   · 숫자 토막 — 이~구·백·천·만(폴더 02). 100 을 넘는 잔액의 **앞자리**에만 쓴다 —
//                 끝 두 자리는 폴더 03 에서 통째로 가져온다(125 → 백 + 이십오)
// 못 읽는 것은 **아이 이름·'지금 기분'·서버가 보낸 거절 안내**다 — 교회 설정과 아이가
// 쓴 글에 딸려 바뀌어 미리 구울 수가 없다. 그 자리는 조용히 지나간다(아래 '다음 걸음').
// 화면에는 그 글이 떠 있으므로, 소리만 비는 것이지 아이가 까닭을 모르는 것은 아니다.
//
// ── 읽는 말 = 화면 글자 ──────────────────────────────────────────
// 토막의 대본은 **디스플레이가 화면에 띄우는 글자와 같게** 둔다. 두 가지를 얻는다:
//   · 안내문 한 줄만 보고 어느 토막을 틀지 고를 수 있다(sound.cpp 의 NOTE_CLIPS)
//   · 나중에 서버가 합성해 보내 주게 되면 **그 글자를 그대로** 읽으면 된다
// 어쩔 수 없이 다른 데가 두 곳이다 — 'PN532' 는 소리로 읽을 말이 아니라 '리더' 로,
// 'WiFi' 는 '와이파이' 로 굽는다.
//
// ── SD 카드 ──────────────────────────────────────────────────────
// 모듈이 알아듣는 짜임새는 폴더 두 자리 · 파일 세 자리다(0x0F 명령).
//   /01/001.mp3 … /01/013.mp3   고정 문구 (아래 SndClip 과 번호가 같다)
//   /02/001.mp3 … /02/014.mp3   숫자 토막 (영·일~구·십·백·천·만) — 100 초과의 앞자리용
//                               (영·일·십 은 쓰이지 않는다. 번호 자리만 지킨다)
//   /03/001.mp3 … /03/101.mp3   0~100 통째 (번호 = 수 + 1)
// 파일을 만드는 스크립트는 **funfunFirmware 쪽에 있다**(tools/make_voices.sh — 맥의
// say -v Yuna + ffmpeg). 두 기기가 같은 표를 쓰므로 스크립트를 두 벌로 두지 않았다:
//   cd ../../funfunFirmware && ./tools/make_voices.sh
//   cp -R voices/01 voices/02 voices/03 /Volumes/<SD>/
// 번호를 바꾸면 **여기와 그 스크립트, 그리고 funfunFirmware/src/sound.h 를 함께** 고칠 것.
// FAT32 로 포맷하고, 폴더 이름은 꼭 두 자리('1' 이 아니라 '01')로 둔다.
//
// ── 배선 ─────────────────────────────────────────────────────────
// config.h 의 '소리' 칸에 있다. 핀은 쓰고 있는 것을 피해 GPIO0(TX)·GPIO1(RX) 이다 —
// PN532 가 4~7, 부저가 10, 선(I2C)이 20·21, USB 가 18·19, 2·8·9 는 부팅 스트래핑.
//
// ── 어디서 소리가 나나 ───────────────────────────────────────────
//   태깅 결과   디스플레이의 답(note·points) → soundSayNote()   ← 거의 다 이것이다
//   디스플레이  {"say":"설정 다시 받는 중"} 따위 → soundSayNote()
//   부팅        '리더 준비 중' (SOUND_SAY_BOOT)
//   PN532 없음  '리더를 찾을 수 없어요'
//   시리얼 voice 토막을 하나씩 차례로 — 스피커·SD·번호를 눈이 아니라 귀로 확인한다
//
// ── 부저는 그대로 둔다 ───────────────────────────────────────────
// 삑·삐-삐 는 없애지 않았다. 말보다 **빠르다** — 모듈이 첫 소리를 내기까지 100ms 가
// 넘는데, 부저는 그 자리에서 울린다. 아이는 삑 소리로 '읽혔다' 를 먼저 알고, 말은
// 그다음에 듣는다. 둘이 겹치는 게 싫으면 config.h 의 SOUND_KEEP_BEEP 를 0 으로.
//
// ── 다음 걸음 — 서버가 합성해 보내 주기 ─────────────────────────
// 아이 이름과 서버의 거절 안내('화요일은 출석을 안 받아요')까지 읽히려면 글자를 소리로
// 바꿀 데가 있어야 한다. DFPlayer 로는 **거기까지 못 간다** — 모듈이 SD 를 혼자 쥐고
// 있어서 ESP32 가 그 카드에 새 mp3 를 써 넣을 길이 없다. 길이 셋이다:
//   (1) 소리 꾸러미 — 서버가 그 교회 설정으로 거절 안내를 미리 구워 /01/020.mp3 부터
//       얹어 주고, 관리자가 SD 에 한 번 복사한다. 지금 하드웨어로 되는 유일한 길이다.
//   (2) I2S DAC 를 따로 붙여(MAX98357A) 자유로운 말만 그쪽으로 흘린다. 이 보드에는
//       아직 GPIO3 이 남아 있지만 I2S 는 세 선(BCLK·LRC·DIN)이 필요해 한 자리가 모자란다 —
//       부저(GPIO10)를 떼면 선다. 다만 소리 꾸러미를 받아 올 쪽은 디스플레이다
//       (이 리더는 와이파이에 붙지 않는다) — 선으로 흘려보낼 길부터 생각해야 한다.
//   (3) 디스플레이가 전부 맡고 리더는 삑만 — 그러면 I2C→UART 다리칩이 다시 필요하다.
// 어느 길로 가든 **읽을 글자를 고르는 곳은 soundSayNote() 하나**로 둔다.
// ─────────────────────────────────────────────────────────────────

#include <Arduino.h>

#include "config.h"

// 폴더 01 — 고정 문구. 번호가 곧 /01/NNN.mp3 다.
// ★ funfunFirmware/tools/make_voices.sh 의 표와 번호·대본이 같아야 한다.
enum SndClip : uint8_t {
  SND_NONE = 0,
  SND_IDLE_PROMPT = 1,   // 카드를 올려 주세요
  SND_BALANCE = 2,       // 잔여 포인트
  SND_ALREADY = 3,       // 이미 출석했어요
  SND_UNKNOWN_CARD = 4,  // 등록되지 않은 키링
  SND_NO_SERVER = 5,     // 서버에 물어보지 못했어요
  SND_CONFIG = 6,        // 설정 다시 받는 중
  SND_READER_INIT = 7,   // 리더 준비 중      (화면은 'PN532 준비 중')
  SND_WIFI = 8,          // 와이파이 붙는 중  (화면은 'WiFi 붙는 중')
  SND_READER_FAIL = 9,   // 리더를 찾을 수 없어요 (화면은 'PN532 · 찾을 수 없음')
  SND_ATTEND_OK = 10,    // 출석 완료   — 뒤에 숫자와 '포인트' 가 붙는다
  SND_POINT = 11,        // 포인트
  SND_ETC = 12,          // 외          — '외 N명'
  SND_PEOPLE = 13,       // 명
};

// 켤 때 한 번. UART 를 열고 모듈이 스스로 설 시간을 센다(전원이 들어온 뒤 1.5초쯤
// 걸린다). 리셋·음량까지는 soundLoop()·soundPump() 가 이어서 한다 — setup 에서 기다려
// 붙잡고 있지 않으려는 것이다.
void soundBegin();

// 본 고리에서 매번. 다 읽었다는 알림을 받아 다음 토막을 밀어 넣는다.
void soundLoop();

// loop 가 아직 안 도는 자리(setup)에서 소리만 돌리며 쉰다.
void soundPump(uint32_t ms);

// 고정 토막 하나를 읽는다. 읽고 있던 것은 끊는다 — 앞 아이의 잔액을 뒷 아이 앞에서
// 계속 읽고 있으면 안 된다.
void soundSay(uint8_t clip);

// 디스플레이가 보낸 안내문 한 줄을 읽는다. 아는 문구면 토막을 이어 붙이고, 모르는
// 문구(서버가 보낸 거절 안내)면 조용히 지나간다. note 가 비어 있으면 잔액을 읽는다.
//   "출석 완료 +5P" → [출석 완료][오][포인트]
//   ""              → [잔여 포인트][오십칠]          잔액이 100 까지면 한 토막
//   ""              → [잔여 포인트][백][이십오]       넘으면 앞자리만 세우고 끝 두 자리는 통째로
//   ""              → [잔여 포인트][천][이][백][오]
void soundSayNote(const char *note, long points);

// 읽던 것을 끊고 줄도 비운다.
void soundStop();

// 소리 크기 0~30.
void soundVolume(uint8_t vol);

// 시리얼 'voice' — 토막을 하나씩 차례로 읽어 본다.
void soundTestNext();

// 시리얼 'status' 에 한 줄 보탠다.
void soundReport();
