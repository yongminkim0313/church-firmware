// ── 리더와 직접 잇는 선 (I2C 마스터) ──────────────────────────────
// 리더(nfcProjectClient, ESP32-C3)를 옆면 4핀 커넥터에 물린다. WebSocket 서버는 그대로
// 열어 둔다 — 브라우저·폰은 계속 ws 로 붙고, 리더만 선으로 온다(둘 다 받는다).
//
// **UART 가 아니라 I2C 인 이유** — 이 보드가 밖으로 내주는 건 옆면 1.25mm 4핀 커넥터
// 하나뿐이다. RGB 패널이 2·3·5·6·7·9~18·21·41·42·45·47 을, SD 가 38·39·40 을, 백라이트가
// 46 을, OPI PSRAM 이 35~37 을 먹는다. 43·44 는 커넥터에 나오지 않고(네이티브 USB 라
// UART 브리지가 없다), 1 은 터치 INT, 4 는 배터리 전압 측정이다. 남는 건 그 커넥터의
// GPIO8(SDA)·GPIO48(SCL) 뿐인데 이미 I2C 다 — 그래서 리더를 이 버스에 슬레이브로 붙인다.
//
//   4핀 커넥터            리더(C3)
//     GND   ───────────    GND          ← 필수
//     GPIO8 (SDA) ─────    GPIO20 (SDA)
//     GPIO48(SCL) ─────    GPIO21 (SCL)
//     3V3   ── 잇지 마라 ─ (리더는 자기 USB 로 먹인다 — 두 레귤레이터를 맞물리지 않는다)
//
// 이 버스에는 터치(0x15)와 화면 확장칩 XL9535(0x20)가 이미 붙어 있다. 리더는 0x30 이라
// 겹치지 않는다. 풀업은 이 보드에 이미 있다.
//
// 슬레이브는 먼저 말을 걸 수 없으니 **이쪽이 마스터로 물어본다** — LINK_POLL_MS 마다
// "줄 것 있나" 하고 읽어 오고, 결과(이름·잔액·출석)는 이쪽이 써 넣어 준다.
#define LINK_I2C_ENABLE  1      // 0 = 선을 안 쓴다(WebSocket 만)
#define LINK_I2C_ADDR 0x30      // 리더의 주소(리더 config.h 의 LINK_I2C_ADDR 과 같아야 한다)
#define LINK_POLL_MS    50      // 리더에게 "줄 것 있나" 를 묻는 주기
#define LINK_IDLE_POLL_MS 1000  // 리더가 LINK_IDLE_AFTER 번 잇달아 답이 없으면 이 주기로 늦춘다
#define LINK_IDLE_AFTER    3    // (코어가 실패마다 에러 두 줄을 찍어 loop 가 늘어지는 것을 막는다)
#define LINK_ALIVE_MS 3000      // 이 시간 안에 리더가 답했으면 선이 살아 있다고 본다

// ── 리더와 선 없이 잇기 (ESP-NOW) ─────────────────────────────────
// 선(I2C)이 1순위인 것은 그대로다. 선이 죽었을 때 넘어가는 2순위를 **WebSocket 에서
// ESP-NOW 로 바꿨다**(2026-10-11). 오가는 글자는 선과 **똑같은 JSON** 이라 푸는 곳은 그대로다.
//
// 왜 바꿨나 — 예전 2순위는 리더가 공유기에 붙고(수 초) mDNS 로 이 화면을 찾아(들쭉날쭉)
// ws 로 접속하는 길이었다. 공유기가 죽으면 그 길도 함께 죽고, mDNS 가 막힌 망에서는
// 고정 IP 를 손으로 적어 줘야 했다. ESP-NOW 는 공유기를 아예 거치지 않는다 — 두 보드가
// 라디오로 바로 말한다. 왕복이 수 ms 고, 공유기가 꺼져 있어도 태깅이 된다.
//
// ★ **두 보드가 같은 와이파이 채널에 있어야 한다.** 이 화면은 공유기에 붙어 있으므로
//   채널을 공유기가 정한다(이쪽에서 고를 수 없다). 그래서 **리더가 채널을 찾아온다** —
//   1~13 을 돌며 부르다가 이 화면이 답하면 그 채널에 자리 잡는다(리더 쪽 espnowHunt).
//   공유기가 채널을 바꾸면 조용해지고, 리더가 다시 찾아 나선다. 손댈 것은 없다.
//
// ★ 짝은 **저절로 맺힌다.** MAC 주소를 적어 둘 필요가 없다 — 리더가 브로드캐스트로 먼저
//   부르면 이쪽이 그 MAC 을 배워 둔다. 보드를 바꿔 끼워도 그대로 된다.
#define ESPNOW_ENABLE 1          // 0 = 선(I2C)만 쓴다

// 우리 둘만 알아듣는 표식. 덩이 앞에 이 글자가 붙어 있지 않으면 버린다 —
// 같은 채널에 다른 ESP-NOW 기기가 있어도 서로 헷갈리지 않게.
// **리더(slave/src/config.h)의 같은 값과 반드시 같아야 한다.**
// 이것은 자물쇠가 아니라 이름표다(엿듣기·흉내는 막지 못한다). 한 교회 안에 리더를
// 여럿 두게 되면 그때 교회마다 다른 값으로 바꿔 주면 된다.
#define ESPNOW_MAGIC "FFP1"

// 리더가 이 시간 안에 무엇이든 보냈으면 라디오 너머에 살아 있다고 본다.
