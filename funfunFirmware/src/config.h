// ── 소리 (DFPlayer Mini · YX5200) ─────────────────────────────────
// 미리 구워 둔 한국어 토막을 이어 읽는다. 합성은 하지 않는다 — 이 모듈이 하는 일은
// 제 microSD 에 든 mp3 를 **번호로 틀어 주는 것**뿐이다. 그래서 읽을 수 있는 말은
// SD 에 들어 있는 것뿐이고, 어떤 토막이 있어야 하는지는 src/sound.h 의 표가 정한다.
