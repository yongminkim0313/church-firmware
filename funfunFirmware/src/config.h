// 0 으로 두면 캐시를 쓰지 않는다(태깅마다 내려받는다).
//
// ★ 칸은 **필요할 때 한 장씩** 잡는다 — 아이가 열 명인데 6.9MB 를 미리 묶어 두지 않는다.
// ★ 캐시 열쇠는 UID 가 아니라 **사진 파일 이름**이다. 이름에 사진 해시가 들어 있어
