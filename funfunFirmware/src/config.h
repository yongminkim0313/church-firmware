//
// 0 으로 두면 소리 쪽이 통째로 빠진다(UART 도 열지 않는다) — 모듈을 안 달고 구울 때.
#define SOUND_ENABLE 1

// UART1. 쓰고 있는 핀을 피했다 — 화면이 4·5·6·7·15·16, PN532 가 9·10·11·12,
// BOOT 버튼이 0, GPIO3 은 이 보드에서 LOW 로 고착, 19·20 은 USB, 33~37 은 옥탈 PSRAM.
// ★ DF_TX 는 **모듈의 RX** 로 간다(이름이 엇갈리니 배선할 때 조심). 모듈은 5V 로
//   돌지만 입력은 3.3V 를 알아듣는다 — 다만 모듈 RX 에 1kΩ 을 끼우는 것이 통례다
//   (전압을 낮추려는 것이 아니라 그 선이 잡음을 타 엉뚱한 명령으로 읽히는 것을 막는다).
// ★ RX 를 꼭 잇는다. 다 읽었다는 알림(0x3D)으로 다음 토막을 밀어 넣기 때문이다 —
//   안 이으면 토막마다 빗장 시간(DF_CLIP_MAX_MS · 5초)을 기다려 말이 뚝뚝 끊긴다.
//   소리는 나는데 "출석 완료 · 오 · 포인트" 가 15초에 걸쳐 나오면 이 선만 빠진 것이다.
#define DF_TX_PIN 17  // ESP32 TX → 모듈 RX (1kΩ 직렬)
#define DF_RX_PIN 18  // ESP32 RX ← 모듈 TX
// 배선: VCC=5V · GND=GND · SPK_1/SPK_2 에 3W 꼬마 스피커(또는 DAC_L/DAC_R 를 앰프로)
//      BUSY 는 쓰지 않는다 — 다 읽었다는 것은 모듈이 UART 로 알려 준다(0x3D).
// ★ 5V 는 데브킷의 5V 핀에서 끌어온다. 소리가 날 때 전류가 확 뛰므로 모듈 VCC 바로
//   옆에 100µF 를 하나 달아라 — 없으면 큰 소리에서 보드가 리셋되는 일이 있다.
//   GND 는 꼭 공통으로 둔다(스피커 전원을 따로 쓰면 UART 가 기준을 잃는다).

// 소리 크기 0~30. 교회 로비에서 22 쯤이 적당했다.
// ★ 나중에 서버 설정(talentConfigV2)에 얹을 자리다 — 밝기(backlight)처럼 관리 화면에서
//   만지게 하려면 여기 기본값을 두고 cfg 로 덮으면 된다(sound.h 의 '다음 걸음' 참고).
