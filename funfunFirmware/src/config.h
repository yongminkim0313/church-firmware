// ★ 부팅 때 깨진 화면을 가리는 일은 이 값과 **상관없다.** 전에는 백라이트를 내려 가렸는데
//   (그래서 BLK 가 없으면 그 한 번이 그대로 비쳤다), 이제는 패널 자체의 화면 끄기로 한다 —
//   선이 있든 없든 똑같이 가려진다(main.cpp 의 setup 참고).
// ★ BLK 가 달린 모듈로 바꾸면 **1 로 되돌릴 것.** 안 되돌리면 그 핀이 떠 있어, 모듈에
