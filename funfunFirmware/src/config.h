#define MDNS_HOSTNAME "lcdtest"

// ── WebSocket 서버 포트 ───────────────────────────────────────────
// 외부(브라우저·폰·리더)가 여기에 붙어 화면 상태를 보낸다: ws://lcdtest.local:81/
#define WS_PORT 81

// ── 펀펀포인트 서버 ───────────────────────────────────────────────
//   운영: "https://funfun.youthvision.co.kr"
//   개발: "http://192.168.0.10:8200"  (자기 PC IP)
// ★ 서버를 바꾸면 보는 자료(잔액·명단)가 통째로 바뀐다 — RTDB 가 서버마다 갈려 있다.
//   저쪽에만 있는 아이는 그 자리에서 '등록되지 않은 키링' 이 된다.
#define TALENT_SERVER "https://funfun.youthvision.co.kr"

// 이 기기의 이름. 관리자 화면 '리더 설정 → v2.0' 에서 이 ID 로 기기별 설정을 덮어쓸 수 있고,
// 포인트 내역에도 어느 기기에서 올라온 것인지 이 이름으로 남는다.
// 영문·숫자·_·- 만 쓴다(서버가 그 밖의 글자를 지운다).
// ★ 운영 기기(nfc-display)와 다른 이름을 쓴다 — 설정과 내역이 섞이지 않게.
#define TALENT_DEVICE_ID "fun-2"

// ── 서버에 붙어 변화 받기 ─────────────────────────────────────────
// 이 보드가 서버에 **client 로 붙어 있는다**. 관리 화면에서 포인트를 조정하거나
// 앱·다른 리더에서 변화가 생기면 서버가 그 아이를 이 화면에 띄우라고 밀어 준다.
// 주소는 따로 적지 않는다 — TALENT_SERVER 에서 호스트·포트·ssl 을 떼어 쓴다.
// 0 으로 두면 전처럼 혼자 돈다(조회·지급은 그대로 — 밀어 주는 것만 안 온다).
#define TALENT_HUB_ENABLE 1
#define TALENT_HUB_PATH "/ws/device"
#define HUB_RETRY_MS 5000UL

// ── 설정 다시 받기 ────────────────────────────────────────────────
// 관리자 화면에서 밝기·출석모드를 바꾸면 이 주기로 기기에 반영된다.
// 와이파이에 붙는 순간에도 한 번 받는다. 시리얼 'c' 로 즉시 받을 수 있다.
#define CONFIG_TTL_MS 300000UL  // 5분

// ── 출석모드 ──────────────────────────────────────────────────────
// 같은 키링이 이 시간 안에 또 오면 출석으로 세지 않는다(화면에는 "이미 출석했어요").
// 기기에 시계(RTC)가 없어 "하루 한 번" 을 알 수 없다 — 시간 간격으로 막는다.
#define ATTEND_COOLDOWN_MS 600000UL  // 10분
#define ATTEND_RECENT_MAX 32         // 최근 출석한 키링을 이만큼 기억한다

// ── 밝기 기본값 ───────────────────────────────────────────────────
// 서버 설정(backlight 1~16)을 못 받았을 때 쓰는 값.
#define BL_LEVEL 16

// ── 버튼 (보드의 BOOT 버튼) ───────────────────────────────────────
// 참고 기기는 화면을 눌렀다(터치). 이 보드엔 터치가 없어 BOOT 버튼으로 대신한다.
// 짧게: 대기 화면으로 · 길게: 설정 다시 받기
#define BTN_PIN 0  // BOOT 버튼 (누르면 LOW)
#define LONG_PRESS_MS 1200

// ── 사진 ──────────────────────────────────────────────────────────
// 태깅할 때마다 서버에서 그 아이 사진을 받아 화면에 깐다(SD 가 없어 모아 두지 않는다).
//   GET /api/talent/roster?px=<TALENT_PX>      → UID 마다 그림 파일 이름(img)
//   GET /api/talent/photo/device/<img>         → <TALENT_PX> 정사각 RGB565(리틀엔디안)
//
// ★ 서버가 만들어 주는 크기는 48·208·480 뿐이다(talentPhoto.js 의 DEVICE_SIZES) —
//   240 은 없다. 그래서 **480 을 받아 기기에서 2:1 로 줄인다**. 480 을 고른 까닭:
//     · 480 은 원형 디스플레이용으로 꽉 찬 동그라미다(바깥은 비침색). 2 로 나누면
//       240 원형 화면에 정확히 들어맞는다. 208 은 모서리만 둥근 정사각이라 둥근
//       화면에서 네 귀가 잘린다.
//     · **사진을 안 올린 아이의 '이름 그림'(nm-…)은 480 에만 있다**
//       (talentPhoto.js 의 NAME_IMAGE_SIZES). 208·48 로 받으면 그 아이들은 그림이 없다.
//   값은 480(2:1 로 줄임) 또는 240(서버에 240 을 추가했다면 그대로 쓴다)만 쓴다.
#define TALENT_PX 240
#define PHOTO_ENABLE 1  // 0 = 사진 없이 글자만

// 이름표(UID→사진 이름)를 들고 있는 칸 수. PSRAM 에 잡는다.
#define MAX_ROSTER 400
// ── 사진 캐시 (PSRAM) ─────────────────────────────────────────────
// 받은 사진을 PSRAM 에 들고 있다가 같은 아이가 또 오면 내려받지 않고 바로 깐다.
// 한 장 = 240*240*2 = 115,200바이트이므로
//     60장 = 6,912,000바이트 (약 6.9MB)
// 이 보드의 가용 PSRAM 이 8,386,096바이트라 72장이 이론상 한계다. 60 으로 둔 까닭:
// 단편화 여유와, 이름표(최대 41,600바이트)·나중에 PSRAM 에 올릴 것들의 자리를 남긴다.
// 0 으로 두면 캐시를 쓰지 않는다(태깅마다 내려받는다).
//
// ★ 칸은 **필요할 때 한 장씩** 잡는다 — 아이가 열 명인데 6.9MB 를 미리 묶어 두지 않는다.
// ★ 캐시 열쇠는 UID 가 아니라 **사진 파일 이름**이다. 이름에 사진 해시가 들어 있어
//   (ph-<해시>-240.565) 아이가 사진을 바꾸면 이름이 달라진다 — 옛 사진을 내보낼 길이 없다.
//   서버 쪽 주석의 "있다 = 최신" 과 같은 원리다.
#define PHOTO_CACHE_MAX 60

// 이름표를 다시 받는 주기. 아이가 사진을 바꾸면 img 이름이 달라지므로 이만큼 뒤에 반영된다.
#define ROSTER_TTL_MS 600000UL  // 10분

#define HTTP_TIMEOUT_MS 6000

// ── 소리 (DFPlayer Mini · YX5200) ─────────────────────────────────
// 미리 구워 둔 한국어 토막을 이어 읽는다. 합성은 하지 않는다 — 이 모듈이 하는 일은
// 제 microSD 에 든 mp3 를 **번호로 틀어 주는 것**뿐이다. 그래서 읽을 수 있는 말은
// SD 에 들어 있는 것뿐이고, 어떤 토막이 있어야 하는지는 src/sound.h 의 표가 정한다.
// 파일은 tools/make_voices.sh 가 만든다(맥의 say + ffmpeg).
//
// 0 으로 두면 소리 쪽이 통째로 빠진다(UART 도 열지 않는다) — 모듈을 안 달고 구울 때.
#define SOUND_ENABLE 1

// UART1. 쓰고 있는 핀을 피했다 — 화면이 4·5·6·7·15·16, PN532 가 9·10·11·12,
// BOOT 버튼이 0, GPIO3 은 이 보드에서 LOW 로 고착, 19·20 은 USB, 33~37 은 옥탈 PSRAM.
// ★ DF_TX 는 **모듈의 RX** 로 간다(이름이 엇갈리니 배선할 때 조심). 모듈은 5V 로
//   돌지만 입력은 3.3V 를 알아듣는다 — 다만 모듈 RX 에 1kΩ 을 끼우는 것이 통례다
//   (전압을 낮추려는 것이 아니라 그 선이 잡음을 타 엉뚱한 명령으로 읽히는 것을 막는다).
#define DF_TX_PIN 17  // ESP32 TX → 모듈 RX (1kΩ 직렬)
#define DF_RX_PIN 18  // ESP32 RX ← 모듈 TX
// 배선: VCC=5V · GND=GND · SPK_1/SPK_2 에 3W 꼬마 스피커(또는 DAC_L/DAC_R 를 앰프로)
//      BUSY 는 쓰지 않는다 — 다 읽었다는 것은 모듈이 UART 로 알려 준다(0x3D).

// 소리 크기 0~30. 교회 로비에서 22 쯤이 적당했다.
// ★ 나중에 서버 설정(talentConfigV2)에 얹을 자리다 — 밝기(backlight)처럼 관리 화면에서
//   만지게 하려면 여기 기본값을 두고 cfg 로 덮으면 된다(sound.h 의 '다음 걸음' 참고).
#define SOUND_VOLUME 22

// 토막과 토막 사이 쉼. 0 으로 두면 숫자가 뭉개져 들린다.
#define SOUND_GAP_MS 60

// 켜질 때 "리더 준비 중 · 와이파이 붙는 중" 을 읽는다 — 상자가 살아 있다는 신호.
#define SOUND_SAY_BOOT 1
