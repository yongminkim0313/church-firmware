#define SUMMARY_TTL_MS 60000UL  // 1분

// ── 대기 화면 네 장 (pages.h) ─────────────────────────────────────
// 홈 → 최근 내역 → 오늘 출석 → 출석 랭킹 → 포인트 랭킹 → 홈 으로 돌아가며 띄운다.
// 받은 것이 없는 장(오늘 아무도 안 왔다 등)은 건너뛴다. BOOT 를 짧게 누르면 다음 장으로.
// 0 으로 두면 예전처럼 홈 한 장만 띄우고 알림판도 받지 않는다.
#define PAGES_ENABLE 1
#define PAGE_HOME_MS 10000UL  // 홈을 띄워 두는 시간
#define PAGE_MS 6000UL        // 나머지 장 하나를 띄워 두는 시간
// 최근 내역이 원 안에 다 안 들면(넷 넘게) 천천히 아래로 굴린다 — 위에서 HOLD 만큼 멈췄다가
// 초당 PX_S 픽셀로 끝까지, 끝에서 HOLD 만큼 멈춘 뒤 다음 장. 그동안 서버 받기는 쉰다.
// 열다섯 줄이면 굴릴 길이가 362px — 20 이면 18초 남짓 걸린다.
#define PAGE_SCROLL_PX_S 20
#define PAGE_SCROLL_HOLD_MS 2500UL
// 알림판(최근 내역 · 오늘 출석 · 순위)을 다시 받는 주기. 포인트가 바뀌면 홈 숫자와 함께
// 주기를 기다리지 않고 받는다.
#define BOARD_TTL_MS 60000UL  // 1분

#define HTTP_TIMEOUT_MS 6000

// ── 소리 (DFPlayer Mini · YX5200) ─────────────────────────────────
// 미리 구워 둔 한국어 토막을 이어 읽는다. 합성은 하지 않는다 — 이 모듈이 하는 일은
// 제 microSD 에 든 mp3 를 **번호로 틀어 주는 것**뿐이다. 그래서 읽을 수 있는 말은
// SD 에 들어 있는 것뿐이고, 어떤 토막이 있어야 하는지는 src/sound.h 의 표가 정한다.
// 파일은 tools/make_voices.sh 가 만든다(맥의 say + ffmpeg).
//
// 0 으로 두면 소리 쪽이 통째로 빠진다(UART 도 열지 않는다) — 모듈을 안 달고 구울 때.
#define SOUND_ENABLE 1

// UART1. 쓰고 있는 핀을 피했다 — 화면이 4·5·6·7·15·16, PN532 가 9·10·11·12,
// BOOT 버튼이 0, GPIO3 은 이 보드에서 LOW 로 고착, 19·20 은 USB, 33~37 은 옥탈 PSRAM.
// ★ DF_TX 는 **모듈의 RX** 로 간다(이름이 엇갈리니 배선할 때 조심). 모듈은 5V 로
//   돌지만 입력은 3.3V 를 알아듣는다 — 다만 모듈 RX 에 1kΩ 을 끼우는 것이 통례다
//   (전압을 낮추려는 것이 아니라 그 선이 잡음을 타 엉뚱한 명령으로 읽히는 것을 막는다).
// ★ RX 를 꼭 잇는다. 다 읽었다는 알림(0x3D)으로 다음 토막을 밀어 넣기 때문이다 —
//   안 이으면 토막마다 빗장 시간(DF_CLIP_MAX_MS · 5초)을 기다려 말이 뚝뚝 끊긴다.
//   소리는 나는데 "출석 완료 · 오 · 포인트" 가 15초에 걸쳐 나오면 이 선만 빠진 것이다.
#define DF_TX_PIN 17  // ESP32 TX → 모듈 RX (1kΩ 직렬)
#define DF_RX_PIN 18  // ESP32 RX ← 모듈 TX
// 배선: VCC=5V · GND=GND · SPK_1/SPK_2 에 3W 꼬마 스피커(또는 DAC_L/DAC_R 를 앰프로)
//      BUSY 는 쓰지 않는다 — 다 읽었다는 것은 모듈이 UART 로 알려 준다(0x3D).
// ★ 5V 는 데브킷의 5V 핀에서 끌어온다. 소리가 날 때 전류가 확 뛰므로 모듈 VCC 바로
//   옆에 100µF 를 하나 달아라 — 없으면 큰 소리에서 보드가 리셋되는 일이 있다.
//   GND 는 꼭 공통으로 둔다(스피커 전원을 따로 쓰면 UART 가 기준을 잃는다).

// 소리 크기 0~30. 교회 로비에서 22 쯤이 적당했다.
// ★ 나중에 서버 설정(talentConfigV2)에 얹을 자리다 — 밝기(backlight)처럼 관리 화면에서
//   만지게 하려면 여기 기본값을 두고 cfg 로 덮으면 된다(sound.h 의 '다음 걸음' 참고).
#define SOUND_VOLUME 22

// 토막과 토막 사이 쉼. 0 으로 두면 숫자가 뭉개져 들린다.
#define SOUND_GAP_MS 60

// 켜질 때 "리더 준비 중 · 와이파이 붙는 중" 을 읽는다 — 상자가 살아 있다는 신호.
#define SOUND_SAY_BOOT 1
// 대기 화면으로 돌아갈 때 "카드를 올려 주세요" 를 읽는다.
// ★ 기본값 0 인 까닭: 태깅이 끝나고 6초 뒤마다 말을 걸어, 줄이 선 현장에서는 끊임없이
//   떠드는 상자가 된다. 조용한 교회에서 한 번씩 부르고 싶으면 1 로.
#define SOUND_SAY_IDLE 0
// 그냥 조회(출석모드가 아닐 때)에서 잔액까지 읽는다.
#define SOUND_SAY_BALANCE 1

// ── 상태 불 (보드에 달린 RGB LED) ─────────────────────────────────
// 빨강·노랑·초록 세 색으로 '지금 쓸 수 있나' 를 멀리서 알린다. 무슨 색이 무엇을
// 뜻하는지와 겹의 짜임새는 src/led.h 머리말에 있다.
//
// 0 으로 두면 불 쪽이 통째로 빠진다 — 켤 때 검정을 한 번 보내 끄고, 그 뒤로는 핀을 건드리지
// 않는다(WS2812 는 받은 색을 전원이 꺼질 때까지 쥐고 있어 한 번은 꺼 줘야 한다).
// 2026-11-06 끔 — 화면이 이미 상태를 보여 주고, 불빛이 거슬렸다. 다시 켜려면 1 (밝기는 아래).
#define LED_ENABLE 0

// ★ 보드 판에 딸려 다르다 — ESP32-S3-DevKitC-1 **v1.1 은 GPIO48**, v1.0 은 GPIO38 이다.
//   불이 안 들어오면 38 로 바꿔 본다(시리얼 'l' 로 색을 하나씩 켜 본다).
//   쓰고 있는 핀과 겹치지 않는다 — 화면이 4·5·6·7·15·16, PN532 가 9·10·11·12,
//   소리가 17·18, BOOT 버튼이 0, 19·20 은 USB, 33~37 은 옥탈 PSRAM 이다.
#define LED_PIN 48

// 밝기 0~255. 꽉 채우면 어두운 로비에서 눈이 아프고 원형 화면에 색이 비친다.
// 15 — 40 은 책상 앞에서 밝았다(2026-11-06 낮춤). 노랑의 녹색이 15*130/255 = 7 이라
// 이보다 더 내리면 노랑이 주황·연두로 흔들린다.
#define LED_BRIGHT 15
// 대기(준비됨) 초록만 더 어둡게 — 아무 일도 없을 때가 거의 다라, 이 색이 밝으면
// 상자가 초록 등이 된다. 무슨 일이 생기면 위의 밝기로 올라가 그 차이가 눈에 띈다.
// 4 는 실물에서 맞춰 본 값이다(8 은 대기 상태로는 밝았다). 낮지만 WS2812 는 이
// 구간에서도 또렷한 초록을 낸다 — 1~2 까지 내리면 색이 흐려지며 흰끼가 돈다.
#define LED_BRIGHT_IDLE 4

// 노랑의 녹색 비중 0~255. (255,255,0) 은 **연두로 보인다** — WS2812 의 녹색 알이
// 적색 알보다 훨씬 밝아서다. 알 묶음마다 조금씩 달라 눈에 노랑으로 들어오는 선을
// 여기서 맞춘다(올리면 연두, 내리면 주황).
#define LED_YELLOW_G 130

// 깜빡임 반 주기(켜짐 400ms · 꺼짐 400ms). 깜빡이는 것은 '와이파이 끊김' 하나다 —
// 봐 달라는 뜻이라서다. 나머지는 가만히 켜 둔다.
#define LED_BLINK_MS 400

// 켜고 이만큼은 못 붙어 있어도 노랑(붙는 중)으로 둔다. 지나면 빨강으로 — 그때는
// '준비 중' 이 아니라 손을 봐야 하는 상태다(공유기가 꺼져 있거나 비밀번호가 바뀌었다).
#define LED_WIFI_GRACE_MS 60000UL
