#pragma once
// ─────────────────────────────────────────────────────────────────
// 소리 — 미리 구워 둔 토막을 이어 읽는다 (DFPlayer Mini · YX5200)
//
// 이 모듈은 합성을 하지 않는다. 제 microSD 에 든 mp3 를 번호로 틀어 주는 것뿐이라,
// **읽을 수 있는 말은 SD 에 들어 있는 것뿐**이다. 그래서 세 묶음을 굽는다:
//   · 고정 문구 — 화면에 그대로 뜨는 안내문(폴더 01)
//   · 0~100     — 한 토막씩 통째로(폴더 03). 소리로 나가는 수는 거의 다 여기다
//   · 숫자 토막 — 이~구·백·천·만(폴더 02). 100 을 넘는 잔액의 **앞자리**에만 쓴다 —
//                 끝 두 자리는 폴더 03 에서 통째로 가져온다(125 → 백 + 이십오)
// 화면에 뜨는 글자 가운데 **아이 이름·'지금 기분'·서버가 보낸 거절 안내**는 못 읽는다 —
// 교회 설정과 아이가 쓴 글에 딸려 바뀌어 미리 구울 수가 없다. 그 자리는 조용히 지나간다
// (아래 '다음 걸음' 참고).
//
// ── 읽는 말 = 화면 글자 ──────────────────────────────────────────
// 토막의 대본은 **화면에 뜨는 글자와 같게** 둔다. 두 가지를 얻는다:
//   · 안내문 한 줄만 보고 어느 토막을 틀지 고를 수 있다(soundSayNote 의 표) — 부르는
//     곳마다 소리 번호를 따로 들고 다니지 않아도 되고, 서버(허브)가 밀어 준 안내문도
//     같은 길로 읽힌다.
//   · 나중에 서버가 합성해 보내 주게 되면 **서버가 보낸 글자를 그대로** 읽으면 된다.
// 어쩔 수 없이 다른 데가 두 곳이다 — 'PN532' 는 소리로 읽을 말이 아니라 '리더' 로,
// 'WiFi' 는 '와이파이' 로 굽는다. 그 둘은 아래 표의 주석에 적어 두었다.
//
// ── SD 카드 ──────────────────────────────────────────────────────
// 모듈이 알아듣는 짜임새는 폴더 두 자리 · 파일 세 자리다(0x0F 명령).
//   /01/001.mp3 … /01/013.mp3   고정 문구 (아래 SndClip 과 번호가 같다)
//   /02/001.mp3 … /02/014.mp3   숫자 토막 (영·일~구·십·백·천·만) — 100 초과의 앞자리용
//                               (영·일·십 은 쓰이지 않는다. 번호 자리만 지킨다)
//   /03/001.mp3 … /03/101.mp3   0~100 통째 (번호 = 수 + 1)
// 파일은 tools/make_voices.sh 가 만든다(맥의 say -v Yuna + ffmpeg). 번호를 바꾸면
// **여기와 그 스크립트를 함께** 고칠 것 — 둘이 어긋나면 엉뚱한 말이 나온다.
// ★ 2026-10-21 부터 nfcProject 도 같은 표·같은 SD 를 쓴다(소리는 리더 쪽에 달렸다 —
//   nfcProject/slave/src/sound.h). 번호를 바꾸면 **그 파일까지 셋**을 함께 고칠 것.
// FAT32 로 포맷하고, 폴더 이름은 꼭 두 자리('1' 이 아니라 '01')로 둔다.
//
// ── 어디서 소리가 나나 ───────────────────────────────────────────
//   태깅        showNfc() 가 안내문 한 줄을 넘긴다 → soundSayNote()
//   부팅        '리더 준비 중' · '와이파이 붙는 중' (SOUND_SAY_BOOT)
//   치명        PN532 를 못 찾았을 때 (그 자리에서 기기가 서므로 soundPump 로 돌린다)
//   버튼 길게   '설정 다시 받는 중'
//   시리얼 'v'  토막을 하나씩 차례로 — 스피커·SD·번호를 눈이 아니라 귀로 확인한다
//
// ── 다음 걸음 — 서버가 합성해 보내 주기 ─────────────────────────
// 아이 이름과 서버의 거절 안내('화요일은 출석을 안 받아요')까지 읽히려면 글자를 소리로
// 바꿀 데가 있어야 한다. DFPlayer 로는 **거기까지 못 간다** — 모듈이 SD 를 혼자 쥐고
// 있어서 ESP32 가 그 카드에 새 mp3 를 써 넣을 길이 없다. 길이 셋이다:
//   (1) 소리 꾸러미 — 서버가 그 교회 설정으로 거절 안내를 미리 구워 /01/020.mp3 부터
//       얹어 주고, 관리자가 SD 에 한 번 복사한다. 지금 하드웨어로 되는 유일한 길이고,
//       설정을 바꿀 때마다 사람 손이 한 번 간다.
//   (2) I2S DAC 를 따로 붙여(MAX98357A) 서버가 준 소리를 흘려 듣는다. 고정 토막은
//       DFPlayer 가 그대로 맡고 자유로운 말만 이쪽으로 — 이 파일의 soundSayNote()
//       아래쪽('모르는 안내문') 한 자리만 갈아 끼우면 된다.
//   (3) DFPlayer 를 걷어내고 전부 I2S 로. 가장 깔끔하지만 SD·플래시에 소리를 둘 자리와
//       받아 오는 왕복(태깅마다 한 번 더)을 감당해야 한다 — 지금 태깅이 조회+사진으로
//       이미 1.3초다.
// 어느 길로 가든 **읽을 글자를 고르는 곳은 soundSayNote() 하나**로 둔다.
// ─────────────────────────────────────────────────────────────────

#include <Arduino.h>

#include "config.h"

// 폴더 01 — 고정 문구. 번호가 곧 /01/NNN.mp3 다.
// ★ tools/make_voices.sh 의 표와 번호·대본이 같아야 한다.
enum SndClip : uint8_t {
  SND_NONE = 0,
  SND_IDLE_PROMPT = 1,   // 카드를 올려 주세요
  SND_BALANCE = 2,       // 잔여 포인트
  SND_ALREADY = 3,       // 이미 출석했어요
  SND_UNKNOWN_CARD = 4,  // 등록되지 않은 키링
  SND_NO_SERVER = 5,     // 서버에 물어보지 못했어요
  SND_CONFIG = 6,        // 설정 다시 받는 중
  SND_READER_INIT = 7,   // 리더 준비 중      (화면은 'PN532 준비 중')
  SND_WIFI = 8,          // 와이파이 붙는 중  (화면은 'WiFi 붙는 중')
  SND_READER_FAIL = 9,   // 리더를 찾을 수 없어요 (화면은 'PN532 · 찾을 수 없음')
  SND_ATTEND_OK = 10,    // 출석 완료   — 뒤에 숫자와 '포인트' 가 붙는다
  SND_POINT = 11,        // 포인트
  SND_ETC = 12,          // 외          — '외 N명'
  SND_PEOPLE = 13,       // 명
};

// 켤 때 한 번. UART 를 열고 모듈이 스스로 설 시간을 센다(전원이 들어온 뒤 1.5초쯤
// 걸린다). 리셋·음량까지는 soundLoop()·soundPump() 가 이어서 한다 — setup 에서 기다려
// 붙잡고 있지 않으려는 것이다.
void soundBegin();

// 본 고리에서 매번. 다 읽었다는 알림을 받아 다음 토막을 밀어 넣는다.
void soundLoop();

// loop 가 아직 안 도는 자리(setup·치명 화면)에서 소리만 돌리며 쉰다.
void soundPump(uint32_t ms);

// 고정 토막 하나를 읽는다. 읽고 있던 것은 끊는다 — 앞 아이의 잔액을 뒷 아이 앞에서
// 계속 읽고 있으면 안 된다.
void soundSay(uint8_t clip);

// 화면에 뜬 안내문 한 줄을 읽는다. 아는 문구면 토막을 이어 붙이고, 모르는 문구(서버가
// 보낸 거절 안내)면 조용히 지나간다. note 가 비어 있으면 잔액을 읽는다.
//   "출석 완료 +5P" → [출석 완료][오][포인트]
//   ""              → [잔여 포인트][오십칠]          잔액이 100 까지면 한 토막
//   ""              → [잔여 포인트][백][이십오]       넘으면 앞자리만 세우고 끝 두 자리는 통째로
//   ""              → [잔여 포인트][천][이][백][오]
void soundSayNote(const char *note, long points);

// 읽던 것을 끊고 줄도 비운다.
void soundStop();

// 소리 크기 0~30.
void soundVolume(uint8_t vol);

// 시리얼 'v' — 토막을 하나씩 차례로 읽어 본다.
void soundTestNext();

// 시리얼 'i' — 지금 상태 한 줄.
void soundReport();
