#pragma once
// ─────────────────────────────────────────────────────────────────
// 상태 불 — 보드에 달린 RGB LED 한 알로 '지금 어떤가' 를 세 색으로 알린다.
//
// 화면은 상자의 **앞**, 아이가 보는 쪽이다. 지나가는 어른(교사·관리자)이 알고 싶은
// 것은 글자가 아니라 한 가지다 — **이게 지금 쓸 수 있나**. 대기 화면의 상태 한 줄
// (main.cpp statusLine 의 "wifi hub attend")은 코앞에서 들여다봐야 읽히고, 태깅 화면이
// 떠 있는 6초 동안은 아예 가려져 있다. 그 자리를 이 불이 메운다.
//
//   빨강  안 된다        와이파이가 끊겼다 · 서버가 답하지 않았다 · 리더를 못 찾았다
//   노랑  하는 중 · 알림  켜지는 중 · 서버에 물어보는 중 · 됐지만 알려 줄 것이 있다
//   초록  됐다           준비됐다(대기) · 조회·출석이 잘 끝났다
//
// 색을 셋으로 묶어 둔 까닭: 멀리서 **곁눈으로** 읽혀야 한다. 여덟 상태를 여덟 색으로
// 두면 색표를 외워야 쓸 수 있고, 그러면 아무도 안 쓴다. 자세한 것은 화면이 말한다.
//
// ── 어느 LED 인가 ────────────────────────────────────────────────
// ESP32-S3-DevKitC-1 에 달린 **WS2812 한 알**이다(다리 셋 달린 보통 LED 가 아니다).
// 색을 내려면 한 선에 비트열을 실어 보내야 해서 digitalWrite 로는 되지 않는다 —
// 코어의 rgbLedWrite() 가 RMT 로 그 비트열을 만들어 준다. 쓰는 핀을 따로 잡아 둘
// 필요도 없고(그 함수가 처음 부를 때 잡는다), 한 번 보내는 데 30µs 쯤이다.
// ★ 핀이 보드 판에 딸려 다르다 — v1.1 은 GPIO48, v1.0 은 GPIO38 이다. 불이 안 들어
//   오면 config.h 의 LED_PIN 을 38 로 바꿔 본다(시리얼 'l' 로 색을 하나씩 켜 본다).
//
// ── 세 겹 ────────────────────────────────────────────────────────
// 밝힐 색은 세 겹에서 고른다 — 위에 있는 것이 이긴다.
//   치명  ledBase(LED_FATAL)   한 번 켜지면 안 내려온다(기기가 거기서 섰다)
//   일중  ledBusy(true/false)  서버에 물어보는 동안. 화면의 금색 고리와 같이 켜진다
//   잠깐  ledFlash/ledTag      태깅 결과를 화면이 띄우는 동안만
//   바탕  ledBase              와이파이가 붙었나 — 아무 일도 없을 때 보이는 색
// 잠깐 겹이 일중 겹에게 지는 까닭: 앞 아이의 초록이 6초 남아 있는데 뒷 아이가 카드를
// 댔으면, 보여 줄 것은 **지금 하는 일**이다.
// ─────────────────────────────────────────────────────────────────

#include <Arduino.h>

#include "config.h"

// 색 고르는 자리는 여기 하나다 — 부르는 쪽은 '무슨 일이 있었나' 만 말한다.
enum LedState : uint8_t {
  LED_BOOT = 0,  // 노랑      켜지는 중 · 아직 와이파이가 없다
  LED_READY,     // 초록(연한) 준비됐다 — 대기 화면
  LED_OFFLINE,   // 빨강 깜빡  와이파이가 끊겼다
  LED_BUSY,      // 노랑      서버에 물어보는 중
  LED_OK,        // 초록      잘 끝났다
  LED_WARN,      // 노랑      됐지만 알림(이미 출석했어요 · 등록되지 않은 키링 · 거절)
  LED_ERROR,     // 빨강      서버가 답하지 않았다
  LED_FATAL,     // 빨강      기기가 섰다 (리더를 못 찾았다 · 화면을 못 열었다)
  LED_STATE_COUNT,
};

// 켤 때 한 번. 첫 색을 바로 밝힌다.
void ledBegin();

// 본 고리에서 매번. 깜빡임을 돌리고, 잠깐 겹이 지났으면 바탕으로 되돌린다.
// 색이 바뀔 때만 핀에 쓴다 — 매번 보내면 RMT 를 헛돌린다.
void ledLoop();

// 바탕색. LED_FATAL 을 한 번 주면 그 뒤로는 아무것도 못 덮는다.
void ledBase(uint8_t st);

// 서버 왕복이 시작·끝났다. main.cpp 의 spinStart()/spinStop() 이 그대로 부른다 —
// 화면의 금색 고리가 도는 동안이 곧 이 불이 노란 동안이다.
void ledBusy(bool on);

// 잠깐 얹는다(ms 뒤 저절로 내려온다).
void ledFlash(uint8_t st, uint32_t ms);

// 태깅 결과 한 줄을 받아 색을 고른다. 화면에 뜬 그 글자를 그대로 넘긴다 —
// sound.h 의 soundSayNote() 와 같은 길이고, 고치는 자리도 나란히 있다.
//   "출석 완료 +5P" · ""        → 초록
//   "이미 출석했어요" · 모르는 안내문 → 노랑
//   "서버에 물어보지 못했어요"        → 빨강
void ledTag(const char *note, bool known, uint32_t ms);

// 시리얼 'l' — 색을 하나씩 몇 초씩 켜 본다(핀이 맞는지, 어느 색인지 눈으로 확인).
void ledTestNext();

// 시리얼 'i' — 지금 상태 한 줄.
void ledReport();
